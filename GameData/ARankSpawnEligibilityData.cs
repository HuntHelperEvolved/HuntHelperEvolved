internal static class ARankSpawnEligibilityData
{
    private readonly record struct EligiblePoint(float X, float Y, uint[] Marks);
    private sealed record TerritoryData(uint[] Marks, EligiblePoint[] Points);

    // Only absorbs float representation noise, never nearby or differently rounded points.
    private const float CoordinateEpsilon = 0.0001f;

    /// <summary>Complete A-rank roster for a supported territory; empty when unknown.</summary>
    internal static uint[] MarksFor(uint territory) =>
        ByTerritory.TryGetValue(territory, out var data) ? data.Marks : Array.Empty<uint>();

    /// <summary>Eligible NameIds, or null when the point cannot be safely classified.</summary>
    internal static uint[]? For(uint territory, SpawnPoint point)
    {
        if ((point.Ranks & SpawnRanks.A) == 0 || !float.IsFinite(point.X) || !float.IsFinite(point.Y)
            || !ByTerritory.TryGetValue(territory, out var data)) return null;
        uint[]? found = null;
        foreach (var candidate in data.Points)
        {
            if (MathF.Abs(candidate.X - point.X) > CoordinateEpsilon
                || MathF.Abs(candidate.Y - point.Y) > CoordinateEpsilon) continue;
            if (found is not null) return null; // Ambiguous coordinates must remain visible.
            found = candidate.Marks;
        }
        return found;
    }

